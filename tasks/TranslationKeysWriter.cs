using System;
using System.Collections.Generic;
using System.Globalization;
using System.Linq;
using System.Security;
using System.Text;

namespace JPKribs.Jellyfin.Base.Tasks;

/// <summary>
/// Writes the TranslationKeys class: one constant per key a plugin can use, so a mistyped key fails to compile and
/// the editor shows each key's US English.
/// </summary>
internal static class TranslationKeysWriter
{
    /// <summary>
    /// Writes the class.
    /// </summary>
    /// <param name="keys">Every key with its US English text.</param>
    /// <param name="ns">The namespace to write it in.</param>
    /// <param name="className">The class name.</param>
    /// <param name="diagnostics">Receives a JPKT014 error for two keys that make the same name.</param>
    /// <returns>The C# source.</returns>
    public static string Write(IReadOnlyDictionary<string, string> keys, string ns, string className, ICollection<TranslationDiagnostic> diagnostics)
    {
        ArgumentNullException.ThrowIfNull(keys);
        ArgumentNullException.ThrowIfNull(diagnostics);

        var code = new StringBuilder();
        code.Append("// <auto-generated/>\n");
        code.Append("// Written by JPKribs.Jellyfin.Base from Localization and the JellyfinString items. Do not edit.\n\n");
        code.Append(CultureInfo.InvariantCulture, $"namespace {ns};\n\n");
        code.Append("/// <summary>\n/// The keys of the plugin's translations, for BaseTranslations.\n/// </summary>\n");
        code.Append(CultureInfo.InvariantCulture, $"internal static class {className}\n{{\n");

        var names = new Dictionary<string, string>(StringComparer.Ordinal);
        var first = true;
        foreach (var (key, text) in keys.OrderBy(k => k.Key, StringComparer.Ordinal))
        {
            var name = Identifier(key);
            name = name == className ? name + "_" : name;
            if (names.TryGetValue(name, out var other))
            {
                diagnostics.Add(new TranslationDiagnostic("JPKT014", true, $"\"{key}\" and \"{other}\" both become {className}.{name}. Rename one of them."));
                continue;
            }

            names[name] = key;
            if (!first)
            {
                code.Append('\n');
            }

            first = false;
            code.Append(CultureInfo.InvariantCulture, $"    /// <summary>{SecurityElement.Escape(OneLine(text))}</summary>\n");
            code.Append(CultureInfo.InvariantCulture, $"    public const string {name} = {Literal(key)};\n");
        }

        code.Append("}\n");
        return code.ToString();
    }

    /// <summary>
    /// Turns a key into a C# name: a character a name cannot hold becomes an underscore, and a keyword is escaped.
    /// </summary>
    /// <param name="key">The key, such as LogLevel.Trace.</param>
    /// <returns>The name, such as LogLevel_Trace.</returns>
    public static string Identifier(string key)
    {
        ArgumentNullException.ThrowIfNull(key);
        var name = new StringBuilder(key.Length + 1);
        foreach (var c in key)
        {
            name.Append(char.IsLetterOrDigit(c) || c == '_' ? c : '_');
        }

        if (name.Length == 0 || char.IsDigit(name[0]))
        {
            name.Insert(0, '_');
        }

        var text = name.ToString();
        return Keywords.Contains(text) ? "@" + text : text;
    }

    private static readonly HashSet<string> Keywords = new(StringComparer.Ordinal)
    {
        "abstract", "as", "base", "bool", "break", "byte", "case", "catch", "char", "checked", "class", "const", "continue",
        "decimal", "default", "delegate", "do", "double", "else", "enum", "event", "explicit", "extern", "false", "finally",
        "fixed", "float", "for", "foreach", "goto", "if", "implicit", "in", "int", "interface", "internal", "is", "lock",
        "long", "namespace", "new", "null", "object", "operator", "out", "override", "params", "private", "protected",
        "public", "readonly", "ref", "return", "sbyte", "sealed", "short", "sizeof", "stackalloc", "static", "string",
        "struct", "switch", "this", "throw", "true", "try", "typeof", "uint", "ulong", "unchecked", "unsafe", "ushort",
        "using", "virtual", "void", "volatile", "while"
    };

    private static string Literal(string text) => "\"" + text.Replace("\\", "\\\\", StringComparison.Ordinal).Replace("\"", "\\\"", StringComparison.Ordinal) + "\"";

    private static string OneLine(string text) => text.Replace("\r", " ", StringComparison.Ordinal).Replace("\n", " ", StringComparison.Ordinal);
}
