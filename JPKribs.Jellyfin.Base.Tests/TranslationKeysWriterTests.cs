using System.Collections.Generic;
using JPKribs.Jellyfin.Base.Tasks;
using Xunit;

namespace JPKribs.Jellyfin.Base.Tests;

/// <summary>Verifies the TranslationKeys class the translations build writes.</summary>
public class TranslationKeysWriterTests
{
    /// <summary>
    /// Each key becomes a constant named for it, documented with its US English.
    /// True: a plugin writes TranslationKeys.MyRequests and the editor shows the text.
    /// False: a key would have no constant, or show the wrong text.
    /// </summary>
    [Fact]
    public void Write_OneDocumentedConstantPerKey()
    {
        var diagnostics = new List<TranslationDiagnostic>();
        var code = TranslationKeysWriter.Write(new Dictionary<string, string> { ["MyRequests"] = "My <Requests> & more", ["LogLevel.Trace"] = "Trace" }, "My.Space", "Keys", diagnostics);
        Assert.Empty(diagnostics);
        Assert.StartsWith("// <auto-generated/>", code, System.StringComparison.Ordinal);
        Assert.Contains("namespace My.Space;", code, System.StringComparison.Ordinal);
        Assert.Contains("internal static class Keys", code, System.StringComparison.Ordinal);
        Assert.Contains("/// <summary>My &lt;Requests&gt; &amp; more</summary>", code, System.StringComparison.Ordinal);
        Assert.Contains("public const string MyRequests = \"MyRequests\";", code, System.StringComparison.Ordinal);
        Assert.Contains("public const string LogLevel_Trace = \"LogLevel.Trace\";", code, System.StringComparison.Ordinal);
    }

    /// <summary>
    /// A key that is not a C# name becomes one.
    /// True: every Jellyfin key compiles.
    /// False: a key with a dot, a leading digit, or a keyword name would break the build.
    /// </summary>
    [Theory]
    [InlineData("Favorites", "Favorites")]
    [InlineData("PlaybackError.ASS_RENDER_ERROR", "PlaybackError_ASS_RENDER_ERROR")]
    [InlineData("3DFormat", "_3DFormat")]
    [InlineData("class", "@class")]
    [InlineData("Größe", "Größe")]
    public void Identifier_MakesACSharpName(string key, string name)
    {
        Assert.Equal(name, TranslationKeysWriter.Identifier(key));
    }

    /// <summary>
    /// Two keys that make one name fail, and a key named like the class is kept apart from it.
    /// True: the class always compiles.
    /// False: two constants would clash, or a member would share its class's name.
    /// </summary>
    [Fact]
    public void Write_ClashingNames_AreJPKT014()
    {
        var diagnostics = new List<TranslationDiagnostic>();
        var code = TranslationKeysWriter.Write(new Dictionary<string, string> { ["A.B"] = "x", ["A_B"] = "y", ["Keys"] = "z" }, "N", "Keys", diagnostics);
        Assert.Equal("JPKT014", Assert.Single(diagnostics).Code);
        Assert.Contains("public const string Keys_ = \"Keys\";", code, System.StringComparison.Ordinal);
    }
}
