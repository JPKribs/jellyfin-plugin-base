// build-types.mjs
// Builds dist/jpkribs_shared.d.ts, the types for the JS bundle, from the TypeScript sources in src/js. It keeps
// only the values the bundle exports, so the typings never offer a helper a plugin cannot import. The types sit in
// a module declaration for any path ending in jpkribs_shared.js, so a plugin's import by its configurationpage
// path picks them up.
// Run it after scripts/bundle.sh, which writes the export list it reads.
//
//   node scripts/build-types.mjs

import { mkdtempSync, readFileSync, readdirSync, rmSync, writeFileSync, existsSync } from 'node:fs';
import { spawnSync } from 'node:child_process';
import { tmpdir } from 'node:os';
import { join, dirname } from 'node:path';
import { fileURLToPath } from 'node:url';

var root = join(dirname(fileURLToPath(import.meta.url)), '..');
var metaPath = join(root, 'dist', 'jpkribs_shared.meta.json');
var outPath = join(root, 'dist', 'jpkribs_shared.d.ts');

// fail
// Prints a reason and stops with a failing exit code.
// Param: message | what went wrong
function fail(message) {
    console.error(message);
    process.exit(1);
}

// statements
// Splits a declaration file into its top level statements, so each can be kept or dropped whole.
// Param: text | the declaration file
// Returns: an array of statement strings
function statements(text) {
    var list = [];
    var current = [];
    var depth = 0;
    var inComment = false;
    text.split('\n').forEach(function (line) {
        if (!current.length && !line.trim()) return;
        current.push(line);
        // A doc comment belongs to the statement after it, and its braces are prose.
        var trimmed = line.trim();
        if (inComment || trimmed.indexOf('/**') === 0) {
            inComment = trimmed.indexOf('*/') === -1;
            return;
        }
        depth += (line.match(/[{(<]/g) || []).length - (line.match(/[})>]/g) || []).length + (line.match(/=>/g) || []).length;
        if (depth <= 0 && /[;}]\s*$/.test(line)) {
            list.push(current.join('\n'));
            current = [];
            depth = 0;
        }
    });
    if (current.length) list.push(current.join('\n'));
    return list;
}

if (!existsSync(metaPath)) fail('Run scripts/bundle.sh first. ' + metaPath + ' is missing.');
var meta = JSON.parse(readFileSync(metaPath, 'utf8'));
var runtime = new Set(Object.values(meta.outputs)[0].exports);

var temp = mkdtempSync(join(tmpdir(), 'jpk-types-'));
var tsc = spawnSync(join(root, 'node_modules', '.bin', 'tsc'), ['-p', join(root, 'tsconfig.json'), '--noEmit', 'false', '--declaration', '--emitDeclarationOnly', '--rootDir', join(root, 'src', 'js'), '--outDir', temp], { encoding: 'utf8' });
if (tsc.status !== 0) fail('tsc could not emit the declarations.\n' + tsc.stdout + tsc.stderr);

var emitted = temp;
var body = [];
var declared = {};
var values = new Set();

readdirSync(emitted).filter(function (f) { return f.endsWith('.d.ts') && f !== 'index.d.ts'; }).sort().forEach(function (file) {
    statements(readFileSync(join(emitted, file), 'utf8')).forEach(function (statement) {
        var code = statement.replace(/^\s*\/\*\*[\s\S]*?\*\/\s*/, '');
        if (/^(import|export \*|export \{)/.test(code)) return;
        var match = /^(export )?(?:declare )?(function|var|let|const|class|interface|type) (\w+)/.exec(code);
        if (!match) fail('Unexpected declaration in ' + file + ':\n' + statement);
        var kind = match[2];
        var name = match[3];
        var isValue = kind === 'function' || kind === 'var' || kind === 'let' || kind === 'const' || kind === 'class';
        // A value the bundle does not export is internal, such as the dom-util helpers.
        if (isValue && !runtime.has(name)) return;
        if (isValue) values.add(name);
        // A function may have several overloads, so only a second file with the name is a collision.
        if (declared[name] && declared[name] !== file) fail('Two files declare ' + name + ': ' + declared[name] + ' and ' + file + '.');
        declared[name] = file;
        body.push(statement.replace(/^(\s*)export declare /m, '$1export ').replace(/^(\s*)declare /m, '$1'));
    });
});
rmSync(temp, { recursive: true, force: true });

var missing = Array.from(runtime).filter(function (name) { return !values.has(name); });
if (missing.length) fail('The bundle exports values the typings lack: ' + missing.join(', '));

var header = [
    '// jpkribs_shared.d.ts',
    '// Types for jpkribs_shared.js, the web components JPKribs.Jellyfin.Base ships. Generated by',
    '// scripts/build-types.mjs from src/js, so edit the sources rather than this file.',
    '',
    "declare module '*jpkribs_shared.js' {"
];
var indented = body.map(function (s) { return s.split('\n').map(function (line) { return line ? '    ' + line : line; }).join('\n'); });
var text = header.concat(indented).join('\n') + '\n}\n';
writeFileSync(outPath, text);
console.log('Typings -> dist/jpkribs_shared.d.ts: ' + values.size + ' values, ' + (Object.keys(declared).length - values.size) + ' types.');
